public class Main {
    public static void main(String[] args){
        System.out.println(Math.max(5, 10));//Função "max" retorna qual o maior número da sequencia
        System.out.println(Math.min(5, 10));//Função "min" retorna qual o menor número da sequencia
        System.out.println(Math.sqrt(64));//Função "sqrt" retorna a raiz quadrada de 64
        System.out.println(Math.abs(-4.7));//Função "abs" remove o sinal negativo
        System.out.println(Math.pow(2, 8));//Função "pow" retorna a potência de 2 elevado a 8
        System.out.println(Math.round(4.6));//Função "round" arredonda o número    
        System.out.println(Math.ceil(4.1));//Função "ceil" arredonda o número para cima    
        System.out.println(Math.floor(4.9));//Função "floor" arredonda o número para baixo
        System.out.println(Math.random());//função "random" gera um numero aleatório

        
    }
    
}
